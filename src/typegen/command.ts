import path from "node:path";
import ts from "typescript";
import type { CompilerFileSystem } from "./file-system.js";
import { createSchemaCompiler } from "./index.js";

/** Host-owned project access; only explicit generation may write artifacts. */
export interface GenerationHost extends CompilerFileSystem {
  /** Persist one generated artifact. Check mode never calls this method. */
  writeFile(file: string, content: string): void;
}

const usage = `Usage: tubular generate --project tsconfig.json --entry src/tools.ts --out generated/schemas.json [--bindings generated/tools.ts] [--functions name,otherName] [--check]

Without --functions, exported function declarations marked with @tubular are selected.
Entry paths are relative to the tsconfig directory; output paths are relative to the current directory.
With --check, verify that the existing output matches without writing it.`;

/** Parse compiler CLI options, generate deterministic artifacts, or fail when --check detects drift. */
export function runGenerateCommand(args: readonly string[], host: GenerationHost): string {
  if (args.length === 0 || args.includes("--help")) {
    return `${usage}\n`;
  }
  if (args[0] !== "generate") throw new Error(usage);
  const flags = new Map<string, string>();
  let check = false;
  for (let i = 1; i < args.length; i += 1) {
    const flag = args[i];
    if (flag === "--check") {
      if (check) throw new Error("Repeated argument: --check");
      check = true;
      continue;
    }
    const value = args[i + 1];
    if (
      !flag ||
      !value ||
      !["--project", "--entry", "--out", "--bindings", "--functions"].includes(flag) ||
      value.startsWith("--") ||
      flags.has(flag)
    ) {
      throw new Error(`Invalid or repeated argument: ${flag ?? ""}\n${usage}`);
    }
    flags.set(flag, value);
    i += 1;
  }
  const projectFlag = flags.get("--project");
  const entry = flags.get("--entry");
  const outputFlag = flags.get("--out");
  if (!projectFlag || !entry || !outputFlag) throw new Error(usage);
  const project = path.resolve(host.getCurrentDirectory(), projectFlag);
  const output = path.resolve(host.getCurrentDirectory(), outputFlag);
  const sourcePath = path.resolve(path.dirname(path.resolve(project)), entry);
  if (
    !output.endsWith(".json") ||
    path.resolve(output) === path.resolve(project) ||
    path.resolve(output) === sourcePath
  ) {
    throw new Error(
      "--out must name a JSON artifact separate from the source and project configuration",
    );
  }
  const explicit = flags.get("--functions");
  const names =
    explicit === undefined
      ? discoverAnnotatedFunctions(sourcePath, host)
      : explicit
          .split(",")
          .map((name) => name.trim())
          .filter(Boolean);
  if (names.length === 0 || new Set(names).size !== names.length) {
    throw new Error("Select one or more unique exported functions using @tubular or --functions.");
  }
  const bindingFlag = flags.get("--bindings");
  const binding =
    bindingFlag === undefined ? undefined : path.resolve(host.getCurrentDirectory(), bindingFlag);
  if (binding !== undefined) {
    if (!/\.(?:ts|mts|cts)$/.test(binding) || binding === output)
      throw new Error("--bindings must name a separate TypeScript output file");
    if (host.fileExists(binding) && !host.readFile(binding)?.startsWith("// Generated by tubular."))
      throw new Error(
        "Refusing to overwrite a binding destination that was not generated by tubular",
      );
  }
  const compiler = createSchemaCompiler({
    tsconfigPath: project,
    entryFile: entry,
    fileSystem: host,
  });
  const schemas = compiler.compileTools(names);
  const artifacts: [string, string][] = [[output, `${JSON.stringify(schemas, null, 2)}\n`]];
  if (binding !== undefined) artifacts.push([binding, compiler.compileBindings(names, binding)]);
  if (check) {
    for (const [file, content] of artifacts) {
      if (host.readFile(file) !== content)
        throw new Error(`Generated schemas or bindings are out of date: ${file}`);
    }
    return `Verified ${artifacts.length} artifact(s) for ${names.length} tool(s)\n`;
  } else {
    for (const [file, content] of artifacts) host.writeFile(file, content);
    return `Generated ${artifacts.length} artifact(s) for ${names.length} tool(s)\n`;
  }
}

/** Find exported functions tagged @tubular in the entry source without executing that module. */
function discoverAnnotatedFunctions(entryPath: string, host: CompilerFileSystem): string[] {
  const text = host.readFile(entryPath);
  if (text === undefined) throw new Error(`Entry file not found: ${entryPath}`);
  const source = ts.createSourceFile(entryPath, text, ts.ScriptTarget.Latest, true);
  const result: string[] = [];
  for (const node of source.statements) {
    if (
      !ts.isFunctionDeclaration(node) ||
      !node.name ||
      !node.modifiers?.some((modifier) => modifier.kind === ts.SyntaxKind.ExportKeyword)
    )
      continue;
    if (ts.getJSDocTags(node).some((tag) => tag.tagName.text === "tubular"))
      result.push(node.name.text);
  }
  return result;
}
